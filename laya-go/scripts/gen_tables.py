def go_str(text):
    import json
    return json.dumps(text, ensure_ascii=False)


def render_lang():
    sys.path.insert(0, REPO)
    from laya import lang

    flat = sorted((lo, hi, name) for name, rs in lang._SCRIPT_RANGES for lo, hi in rs)
    for (a_lo, a_hi, a_name), (b_lo, b_hi, b_name) in zip(flat, flat[1:]):
        if a_hi >= b_lo:
            raise SystemExit("gen_tables: script ranges %s and %s overlap, so the sorted lookup "
                             "would lose the first-match rule" % (a_name, b_name))
    names = [name for name, _ in lang._SCRIPT_RANGES]
    index_of = {name: n for n, name in enumerate(names)}

    def word_set(words):
        return "newSet(%s)" % ", ".join(go_str(w) for w in sorted(words))

    out = [header("laya/lang.py"), "package lang\n\n"]
    out.append("// The named non-Latin scripts, in the order lang.py declares them.\nconst (\n%s)\n\n"
               % "".join("\t%s Script = %s\n" % (("Script" + n.capitalize()).ljust(max(len(x) for x in names) + 6),
                                               go_str(n)) for n in names))
    out.append("// scriptNames indexes those scripts by their position in lang.py's table.\n"
               "var scriptNames = [...]Script{%s}\n\n"
               % ", ".join("Script%s" % n.capitalize() for n in names))
    out.append("// scriptLookup is every script range sorted by code point, as inclusive lo, hi\n"
               "// pairs; scriptLookupIndex names the script each pair belongs to. They replace\n"
               "// lang.py's ordered scan, which they equal because no two ranges overlap (the\n"
               "// generator refuses an overlap).\n"
               "var scriptLookup = [...]rune{\n%s\n}\n\n" % wrap([v for lo, hi, _ in flat for v in (lo, hi)]))
    out.append("var scriptLookupIndex = [...]uint8{\n%s\n}\n\n" % wrap([index_of[n] for _, _, n in flat]))
    out.append("const scriptMaxCodePoint = %#x\n\n" % max(hi for _, hi, _ in flat))
    out.append("// stopLists are the function words per language, in the order lang.py declares them:\n"
               "// the language that wins a tied score is the first one listed.\n"
               "var stopLists = [...]stopList{\n")
    for code, words in lang._STOP.items():
        out.append("\t{%s, %s},\n" % (go_str(code), word_set(words)))
    out.append("}\n\n")
    for name, words, doc in (
        ("shortSwedishWords", lang._SHORT_SWEDISH_WORDS,
         "Distinctive Swedish words that name the language from a short input."),
        ("sharedWords", lang._SHARED_WORDS,
         "Function words several lists hold, which therefore name no language."),
        ("nordicOverlapWords", lang._NORDIC_OVERLAP_WORDS,
         "Markers shared by Swedish and Danish: evidence of non-English, not of which."),
        ("enOnlyWords", lang._EN_ONLY_WORDS, "English function words no other list holds."),
        ("enCollisionWords", lang._EN_COLLISION_WORDS,
         "Words that collide with English, counted once however often they repeat."),
    ):
        out.append("// %s %s\nvar %s = %s\n\n" % (name, doc, name, word_set(words)))
    diac = sorted(ord(c) for c in lang._NON_EN_DIACRITICS)
    assert all(len(c) == 1 for c in lang._NON_EN_DIACRITICS)
    out.append("// nonEnDiacritics are the letters whose presence is evidence the text is not\n"
               "// English, sorted by code point.\nvar nonEnDiacritics = [...]rune{\n%s\n}\n\n" % wrap(diac))
    consts = (("nonEnDiacriticRate", lang.NON_EN_DIACRITIC_RATE),
              ("englishRescueDiacriticRate", lang.ENGLISH_RESCUE_DIACRITIC_RATE),
              ("nonLatinFraction", lang.NON_LATIN_FRACTION),
              ("nonLatinMinFraction", lang.NON_LATIN_MIN_FRACTION),
              ("nonLatinMinLetters", lang.NON_LATIN_MIN_LETTERS))
    width = max(len(name) for name, _ in consts)
    out.append("const (\n%s)\n" % "".join("\t%s = %r\n" % (name.ljust(width), value)
                                         for name, value in consts))
    return "".join(out)


def render_lang_cpp():
    """laya.lang's script ranges, function words and thresholds, as a C++ include for src/lang.cpp."""
    sys.path.insert(0, REPO)
    from laya import lang

    flat = sorted((lo, hi, name) for name, rs in lang._SCRIPT_RANGES for lo, hi in rs)
    for (a_lo, a_hi, a_name), (b_lo, b_hi, b_name) in zip(flat, flat[1:]):
        if a_hi >= b_lo:
            raise SystemExit("gen_tables: script ranges %s and %s overlap" % (a_name, b_name))
    names = [name for name, _ in lang._SCRIPT_RANGES]
    index_of = {name: n for n, name in enumerate(names)}

    def words(name, ws):
        return "inline constexpr const char* %s[] = {\n%s\n};\n\n" % (
            name, wrap([go_str(w) for w in sorted(ws)], indent="    "))

    out = ["// Code generated by laya-go/scripts/gen_tables.py --lang cpp from laya/lang.py; DO NOT EDIT.\n"
           "//\n// Regenerate with: python laya-go/scripts/gen_tables.py --lang cpp\n\n"]
    out.append("inline constexpr const char* k_script_names[] = {%s};\n\n" % ", ".join(go_str(n) for n in names))
    out.append(cpp_array("k_script_lookup", [v for lo, hi, _ in flat for v in (lo, hi)]))
    out.append(cpp_array("k_script_lookup_index", [index_of[n] for _, _, n in flat], "uint8_t"))
    out.append("inline constexpr uint32_t k_script_max_code_point = %#x;\n\n" % max(hi for _, hi, _ in flat))
    stops = list(lang._STOP.items())
    for n, (code, ws) in enumerate(stops):
        out.append(words("k_stop_%d" % n, ws))
    out.append("struct StopSpec { const char* code; const char* const* words; size_t count; };\n"
               "// In lang.py declaration order: the language that wins a tied score is the first listed.\n"
               "inline constexpr StopSpec k_stop_lists[] = {\n%s\n};\n\n"
               % "\n".join("    {%s, k_stop_%d, %d}," % (go_str(c), n, len(ws)) for n, (c, ws) in enumerate(stops)))
    for name, ws in (("k_short_swedish", lang._SHORT_SWEDISH_WORDS), ("k_shared", lang._SHARED_WORDS),
                     ("k_nordic_overlap", lang._NORDIC_OVERLAP_WORDS), ("k_en_only", lang._EN_ONLY_WORDS),
                     ("k_en_collision", lang._EN_COLLISION_WORDS)):
        out.append(words(name, ws))
    out.append(cpp_array("k_non_en_diacritics", sorted(ord(c) for c in lang._NON_EN_DIACRITICS)))
    for name, value in (("k_non_en_diacritic_rate", lang.NON_EN_DIACRITIC_RATE),
                        ("k_english_rescue_diacritic_rate", lang.ENGLISH_RESCUE_DIACRITIC_RATE),
                        ("k_non_latin_fraction", lang.NON_LATIN_FRACTION),
                        ("k_non_latin_min_fraction", lang.NON_LATIN_MIN_FRACTION)):
        out.append("inline constexpr double %s = %r;\n" % (name, value))
    out.append("inline constexpr int k_non_latin_min_letters = %d;\n" % lang.NON_LATIN_MIN_LETTERS)
    return "".join(out)


