def render_unicode(cpp=False):
    word = re.compile(r"[^\W\d_]", re.UNICODE)
    digit = re.compile(r"\d", re.UNICODE)
    preds = [
        ("alpha", "Python's str.isalpha(): categories Lu, Ll, Lt, Lm and Lo.",
         lambda cp: chr(cp).isalpha()),
        ("word", "Python's [^\\W\\d_]: letters plus the Nl and No numeric categories.",
         lambda cp: word.fullmatch(chr(cp)) is not None),
        ("combining", "Code points with a non-zero canonical combining class.",
         lambda cp: unicodedata.combining(chr(cp)) != 0),
        ("digit", "Python's \\d: the Nd category.", lambda cp: digit.fullmatch(chr(cp)) is not None),
        ("upper", "Python's str.isupper() for one character.", lambda cp: chr(cp).isupper()),
        ("lower", "Python's str.islower() for one character.", lambda cp: chr(cp).islower()),
        ("space", "Python's str.isspace().", lambda cp: chr(cp).isspace()),
        ("printable", "Python's str.isprintable(), which is what repr leaves unescaped.",
         lambda cp: chr(cp).isprintable()),
        ("mark", "The Mn, Mc and Me categories, which laya/email.py spells unicodedata.category(ch)\n"
         "// startswith(\"M\").", lambda cp: unicodedata.category(chr(cp)).startswith("M")),
        ("initial", "The Lu, Lt and Lo categories: a letter that is not lowercase.",
         lambda cp: unicodedata.category(chr(cp)) in ("Lu", "Lt", "Lo")),
        ("title", "The Lt category: cased, but neither upper nor lower, so str.isupper() on a\n"
         "// string holding one is false.", lambda cp: unicodedata.category(chr(cp)) == "Lt"),
    ]
    out = [header("CPython %d.%d (Unicode %s)" % (sys.version_info[:2] + (unicodedata.unidata_version,))),
           "package unicodedata\n\n"
           "// Version is the Unicode release these tables were recorded from.\n"
           "const Version = %r\n\n" % unicodedata.unidata_version]
    out[-1] = out[-1].replace("'", '"')
    pred_tables = []
    for name, doc, pred in preds:
        rows = ranges(pred)
        pred_tables.append((name, rows, pred))
        out.append(table(name, rows, doc))
        out.append(ascii_masks(name, lambda cp, p=pred: p(cp)))

    simple, multi = [], []
    for cp in range(MAX):
        if cp in SURROGATES:
            continue
        low = chr(cp).lower()
        if len(low) > 1:
            multi.append((cp, [ord(c) for c in low]))
        elif low != chr(cp):
            simple.append((cp, ord(low)))
    out.append("// lowerFrom lists every code point whose lowercase is one different code point;\n"
               "// lowerTo holds what each maps to.\nvar lowerFrom = [...]rune{\n%s\n}\n\n"
               % wrap([c for c, _ in simple]))
    out.append("var lowerTo = [...]rune{\n%s\n}\n\n" % wrap([t for _, t in simple]))
    out.append("// lowerMulti holds the lowercase of a code point that lowercases to several.\n"
               "var lowerMulti = map[rune][]rune{\n%s\n}\n\n"
               % "\n".join("\t%#x: {%s}," % (cp, ", ".join("%#x" % c for c in low))
                           for cp, low in multi))

    # Final sigma (Greek capital sigma lowercases to U+03C2 at a word end, U+03C3 elsewhere) is
    # context-dependent in CPython, so it is recorded by behaviour rather than from a property:
    #   P1 = 'A' + ch + SIGMA  is final iff ch is case-ignorable OR (cased and not ignorable)
    #   P2 = 'A' + SIGMA + ch  is final iff NOT (cased and not ignorable)
    # which separates the two sets exactly.
    sigma = "Σ"
    blocking, ignorable = [], []
    for cp in range(MAX):
        if cp in SURROGATES:
            continue
        ch = chr(cp)
        p1 = ("A" + ch + sigma).lower()[-1] == "ς"
        p2 = ("A" + sigma + ch).lower()[1] == "ς"
        if not p2:
            blocking.append(cp)
        if p1 and p2:
            ignorable.append(cp)

    def runs(cps):
        rows, start, prev = [], None, None
        for cp in cps:
            if start is None:
                start = prev = cp
            elif cp == prev + 1:
                prev = cp
            else:
                rows.append((start, prev))
                start = prev = cp
        if start is not None:
            rows.append((start, prev))
        return rows

    out.append(table("cased", runs(blocking),
                     "Code points that make a capital sigma non-final when they follow it, and\n"
                     "// final when they precede it: cased and not case-ignorable."))
    out.append(table("caseIgnorable", runs(ignorable),
                     "Case-ignorable code points, which final-sigma detection skips."))
    if cpp:
        return render_unicode_cpp(pred_tables, simple, multi, runs(blocking), runs(ignorable))
    return "".join(out)


def cpp_array(name, values, ctype="uint32_t"):
    return "inline constexpr %s %s[] = {\n%s\n};\n\n" % (ctype, name, wrap(values, indent="    "))


def render_unicode_cpp(pred_tables, simple, multi, cased_rows, ignorable_rows):
    """The same CPython tables as render_unicode, as a C++ include for laya-cpp/src/unicodedata.cpp."""
    out = ["// Code generated by laya-go/scripts/gen_tables.py --lang cpp from CPython %d.%d (Unicode %s); "
           "DO NOT EDIT.\n//\n// Regenerate with: python laya-go/scripts/gen_tables.py --lang cpp\n\n"
           "inline constexpr const char* kUnicodeVersion = \"%s\";\n\n"
           % (sys.version_info[:2] + (unicodedata.unidata_version, unicodedata.unidata_version))]
    for name, rows, pred in pred_tables:
        flat = [v for row in rows for v in row]
        out.append(cpp_array("k_" + name, flat))
        low = sum(1 << cp for cp in range(0, 64) if pred(cp))
        high = sum(1 << (cp - 64) for cp in range(64, 128) if pred(cp))
        out.append("inline constexpr uint64_t k_%s_ascii[2] = {%#x, %#x};\n\n" % (name, low, high))
    out.append(cpp_array("k_lower_from", [c for c, _ in simple]))
    out.append(cpp_array("k_lower_to", [t for _, t in simple]))
    assert all(len(low) <= 3 for _, low in multi)
    out.append("struct LowerMulti { uint32_t from; uint32_t count; uint32_t to[3]; };\n"
               "inline constexpr LowerMulti k_lower_multi[] = {\n%s\n};\n\n"
               % "\n".join("    {%#x, %d, {%s}}," % (cp, len(low), ", ".join("%#x" % c for c in low + [0] * (3 - len(low))))
                          for cp, low in multi))
    out.append(cpp_array("k_cased", [v for row in cased_rows for v in row]))
    out.append(cpp_array("k_case_ignorable", [v for row in ignorable_rows for v in row]))
    return "".join(out)


