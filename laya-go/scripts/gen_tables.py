# The tokenizers crate: pre-tokenizer classes, single_word flank, lowercase, normalization.
# ---------------------------------------------------------------------------------------------
def render_tokenizer(cpp=False):
    import tokenizers
    from tokenizers import AddedToken, Tokenizer, models, normalizers, pre_tokenizers

    if cpp:
        out = ["// Code generated by laya-go/scripts/gen_tables.py --lang cpp from tokenizers %s; DO NOT EDIT.\n//\n"
               "// Regenerate with: python laya-go/scripts/gen_tables.py --lang cpp\n\n"
               "inline constexpr const char* kTokenizerReference = \"tokenizers %s\";\n\n"
               % (tokenizers.__version__, tokenizers.__version__)]
    else:
        out = [header("tokenizers %s" % tokenizers.__version__), "package tokenizer\n\n"]
        out.append("// Reference names the implementation the tables below were probed from.\n"
                   "const Reference = \"tokenizers %s\"\n\n" % tokenizers.__version__)

    def rng(go_name, cpp_name, rows, doc):
        if not cpp:
            return table(go_name, rows, doc)
        flat = [v for row in rows for v in row]
        return tok_array(True, go_name, cpp_name, flat, "%s\n// %d ranges covering %d code points."
                         % (doc.replace("\n//", "\n//"), len(rows), sum(b - a + 1 for a, b in rows)))

    # Letter / number: "a<cp>" stays ONE piece only if ` ?\p{L}+` consumed the code point;
    # "1<cp>" only if ` ?\p{N}+` did. Anything else splits.
    pre = pre_tokenizers.ByteLevel(add_prefix_space=False, use_regex=True)

    def one_piece(prefix):
        def test(cp):
            try:
                return len(pre.pre_tokenize_str(prefix + chr(cp))) == 1
            except Exception:
                return False
        return test

    out.append(rng("letter", "k_letter", ranges(one_piece("a")),
                     "letter is the pre-tokenizer pattern's \\p{L}, probed from the reference."))
    out.append(rng("number", "k_number", ranges(one_piece("1")),
                     "number is the pre-tokenizer pattern's \\p{N}, probed from the reference."))

    # single_word: an added token is refused when the adjacent character is a word character.
    tok = Tokenizer(models.BPE(vocab={"a": 0}, merges=[], unk_token=None))
    tok.add_tokens([AddedToken("TOK", single_word=True)])
    tid = tok.token_to_id("TOK")

    def flanks(cp):
        try:
            left = tid not in tok.encode(chr(cp) + "TOK").ids
            right = tid not in tok.encode("TOK" + chr(cp)).ids
        except Exception:
            return False
        if left != right:
            raise SystemExit("gen_tables: single_word treats U+%04X differently on each side" % cp)
        return left

    out.append(rng("wordChar", "k_word_char", ranges(flanks),
                     "wordChar is what the reference counts as a word character beside a\n"
                     "// single_word added token."))

    # Lowercase, per code point. The crate lowercases character by character (no final sigma).
    low = normalizers.Lowercase()
    simple, multi = [], []
    for cp in range(MAX):
        if cp in SURROGATES:
            continue
        mapped = low.normalize_str(chr(cp))
        if mapped == chr(cp):
            continue
        if len(mapped) == 1:
            simple.append((cp, ord(mapped)))
        else:
            multi.append((cp, [ord(c) for c in mapped]))
    if cpp:
        out.append(tok_array(True, "", "k_lower_from", [c for c, _ in simple], "lowercase, one code point to one"))
        out.append(tok_array(True, "", "k_lower_to", [t for _, t in simple], "the lowercase of k_lower_from"))
        assert all(len(m) <= 3 for _, m in multi)
        out.append("struct TokLowerMulti { uint32_t from; uint32_t count; uint32_t to[3]; };\n"
                   "inline constexpr TokLowerMulti k_lower_multi[] = {\n%s\n};\n\n"
                   % "\n".join("    {%#x, %d, {%s}}," % (cp, len(m), ", ".join("%#x" % c for c in m + [0] * (3 - len(m))))
                              for cp, m in multi))
    else:
        out.append("var lowerFrom = [...]rune{\n%s\n}\n\n" % wrap([c for c, _ in simple]))
        out.append("var lowerTo = [...]rune{\n%s\n}\n\n" % wrap([t for _, t in simple]))
        out.append("var lowerMulti = map[rune][]rune{\n%s\n}\n\n"
                   % "\n".join("\t%#x: {%s}," % (cp, ", ".join("%#x" % c for c in m)) for cp, m in multi))

    out.append(render_normalization(normalizers, cpp))
    return "".join(out)


def render_normalization(normalizers, cpp=False):
    nfc, nfd = normalizers.NFC(), normalizers.NFD()
    nfkd = normalizers.NFKD()
    canon, compat = {}, {}
    for cp in range(MAX):
        if cp in SURROGATES or cp in HANGUL:
            continue
        ch = chr(cp)
        d = nfd.normalize_str(ch)
        k = nfkd.normalize_str(ch)
        if d != ch:
            canon[cp] = [ord(c) for c in d]
        if k != d:
            compat[cp] = [ord(c) for c in k]

    # Canonical combining class, probed from the crate and NOT taken from CPython: the crate
    # reorders against a different set (56 marks CPython gives a class, such as U+07FD and U+0C3C,
    # never reorder in it). A mark sorts before one of higher class, so X swaps with a reference
    # mark of class v exactly when 0 < ccc(X) < v. References are CPython marks accepted only if
    # the crate orders them consistently with the marks accepted before them.
    def swaps(x, mark, before):
        pair = mark + x if before else x + mark
        return nfd.normalize_str(pair) != pair

    refs = {}
    for cp in range(MAX):
        if cp in SURROGATES:
            continue
        c = unicodedata.combining(chr(cp))
        if not c or c in refs or nfd.normalize_str(chr(cp)) != chr(cp):
            continue
        ch = chr(cp)
        if all(swaps(ch, other, True) == (u > c) and swaps(ch, other, False) == (c > u)
               for u, other in refs.items()):
            refs[c] = ch
    values = sorted(refs)
    top, bottom = refs[values[-1]], refs[values[0]]

    def probe_ccc(cp):
        x = chr(cp)
        top_swap = swaps(x, top, True)
        if not top_swap:
            return values[-1] if swaps(x, bottom, False) else 0
        for i, v in enumerate(values):
            if swaps(x, refs[v], True):
                return values[i - 1] if i else 0
        return values[-1]

    ccc = {}
    for cp in range(MAX):
        if cp in SURROGATES or nfd.normalize_str(chr(cp)) != chr(cp):
            continue
        probed = probe_ccc(cp)
        if probed:
            ccc[cp] = probed
    # Where the crate's classes differ from CPython's. Reported, not asserted: the crate is the
    # reference, and a class it does not know is simply a starter to it.
    differing = [cp for cp in range(MAX) if cp not in SURROGATES
                 and nfd.normalize_str(chr(cp)) == chr(cp)
                 and ccc.get(cp, 0) != unicodedata.combining(chr(cp))]
    print("gen_tables: %d refs; the crate's combining class differs from CPython's at %d code points"
          % (len(refs), len(differing)), file=sys.stderr)
    rows, start, prev, val = [], None, None, None
    for cp in sorted(ccc):
        if start is not None and cp == prev + 1 and ccc[cp] == val:
            prev = cp
            continue
        if start is not None:
            rows.append((start, prev, val))
        start = prev = cp
        val = ccc[cp]
    rows.append((start, prev, val))

    # Composition pairs: for each code point that recomposes from its own decomposition, the
    # pair is (compose(all but the last), last). Each is then re-verified against the crate.
    pairs = {}
    for cp, d in canon.items():
        if len(d) < 2 or nfc.normalize_str("".join(map(chr, d))) != chr(cp):
            continue
        first = nfc.normalize_str("".join(map(chr, d[:-1])))
        if len(first) != 1 or nfc.normalize_str(first + chr(d[-1])) != chr(cp):
            raise SystemExit("gen_tables: cannot express U+%04X as a composition pair" % cp)
        pairs[(ord(first), d[-1])] = cp
    keys = sorted(pairs)

    def pool(mapping, name, doc):
        ks = sorted(mapping)
        offsets, flat = [0], []
        for k in ks:
            flat.extend(mapping[k])
            offsets.append(len(flat))
        if cpp:
            return (tok_array(True, "", "k_%s_keys" % name, ks, doc)
                    + tok_array(True, "", "k_%s_offsets" % name, offsets, "offsets into k_%s_pool" % name)
                    + tok_array(True, "", "k_%s_pool" % name, flat, "the decompositions of k_%s_keys" % name))
        return ("// %s\nvar %sKeys = [...]rune{\n%s\n}\n\nvar %sOffsets = [...]uint32{\n%s\n}\n\n"
                "var %sPool = [...]rune{\n%s\n}\n\n"
                % (doc, name, wrap(ks), name, wrap(offsets), name, wrap(flat)))

    text = []
    text.append(pool(canon, "canon", "canon* hold the full canonical decomposition (NFD) of every code\n"
                     "// point that has one, except Hangul syllables, which are algorithmic."))
    text.append(pool(compat, "compat", "compat* hold the full compatibility decomposition (NFKD) of every code\n"
                     "// point where it differs from the canonical one."))
    ccc_doc = "cccRanges are (lo, hi, class) triples of the canonical combining class, sorted."
    comp_doc = "composeKeys are (first<<32 | second) of each primary composition pair, sorted;\n// composeValues is the composite."
    if cpp:
        text.append(tok_array(True, "", "k_ccc_ranges", [v for r in rows for v in r], ccc_doc))
        text.append(tok_array(True, "", "k_compose_keys", ["%#xULL" % ((a << 32) | b) for a, b in keys], comp_doc, "uint64_t"))
        text.append(tok_array(True, "", "k_compose_values", [pairs[k] for k in keys], "the composite of k_compose_keys"))
        return "".join(text)
    text.append("// %s\nvar cccRanges = [...]rune{\n%s\n}\n\n" % (ccc_doc, wrap([v for r in rows for v in r])))
    text.append("// %s\nvar composeKeys = [...]uint64{\n%s\n}\n\n"
                % (comp_doc, wrap(["%#x" % ((a << 32) | b) for a, b in keys])))
    text.append("var composeValues = [...]rune{\n%s\n}\n" % wrap([pairs[k] for k in keys]))
    return "".join(text)


TARGETS = ((OUT_UNICODE, render_unicode), (OUT_LANG, render_lang), (OUT_TOKENIZER, render_tokenizer))
# laya-cpp generated tables.
CPP_TARGETS = ((OUT_CPP_UNICODE, lambda: render_unicode(cpp=True)), (OUT_CPP_LANG, render_lang_cpp),
               (OUT_CPP_TOKENIZER, lambda: render_tokenizer(cpp=True)))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="do not write; exit 1 if a committed copy would change")
    parser.add_argument("--lang", choices=("go", "cpp"), default="go",
                        help="which port's tables to write or check (default go)")
    args = parser.parse_args(argv)
    stale = 0
    for path, render in (CPP_TARGETS if args.lang == "cpp" else TARGETS):
        fresh = render().rstrip("\n") + "\n"
        rel = os.path.relpath(path, REPO)
        if args.check:
            try:
                with open(path, encoding="utf-8") as handle:
                    current = handle.read()
            except OSError:
                current = None
            if current != fresh:
                print("gen_tables: %s is stale; run laya-go/scripts/gen_tables.py and commit it" % rel,
                      file=sys.stderr)
                stale += 1
            else:
                print("gen_tables: %s matches" % rel)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(fresh)
            print("wrote %s (%d bytes)" % (rel, len(fresh.encode("utf-8"))))
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
