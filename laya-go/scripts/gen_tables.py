#!/usr/bin/env python3
"""Generate laya-go's compiled-in Unicode and language tables as Go source.

Three files, three sources, and the split is the point:

  * internal/unicodedata/tables_gen.go -- recorded from CPython (the header names the minor
    version and the Unicode release, never the patch: the tables are a function of the Unicode
    database, which a patch release does not change, and a patch in the header made --check fail
    on every runner whose interpreter was not the one the file was generated on), because `laya/lang.py` is
    written against `str.isalpha()`, `str.lower()` and `re`'s `\\w`, and Go's own `unicode`
    package follows whichever Unicode the Go toolchain ships (it moves between releases).
  * lang/tables_gen.go -- read straight from `laya.lang`: the script ranges, the per-language
    function words and the thresholds.
  * tokenizer/tables_gen.go -- probed from the `tokenizers` crate (the reference the
    Python package tokenizes with), whose Unicode is NOT CPython's: it classifies Unicode 15.1/16
    additions as letters and decomposes 135 code points CPython does not.

Everything is regenerated, never edited. `--check` fails when a committed file differs.

    python laya-go/scripts/gen_tables.py            # write
    python laya-go/scripts/gen_tables.py --check    # fail if a committed copy is stale
"""
import argparse
import os
import re
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
GO = os.path.normpath(os.path.join(HERE, ".."))
REPO = os.path.dirname(GO)
MAX = 0x110000
SURROGATES = range(0xD800, 0xE000)
HANGUL = range(0xAC00, 0xD7A4)
OUT_UNICODE = os.path.join(GO, "internal", "unicodedata", "tables_gen.go")
OUT_LANG = os.path.join(GO, "lang", "tables_gen.go")
OUT_TOKENIZER = os.path.join(GO, "tokenizer", "tables_gen.go")
OUT_CPP_UNICODE = os.path.join(REPO, "laya-cpp", "src", "unicodedata_tables.inc")
OUT_CPP_LANG = os.path.join(REPO, "laya-cpp", "src", "lang_tables.inc")
OUT_CPP_TOKENIZER = os.path.join(REPO, "laya-cpp", "src", "tokenizer_tables.inc")


def wrap(values, indent="\t", width=100):
    """Comma-separated items wrapped to `width`, one trailing comma, ready for a Go literal."""
    lines, current = [], indent
    for item in values:
        piece = str(item) + ", "
        if len(current) + len(piece) > width and current.strip():
            lines.append(current.rstrip())
            current = indent
        current += piece
    if current.strip():
        lines.append(current.rstrip())
    return "\n".join(lines)


def ranges(predicate):
    """Inclusive (lo, hi) runs where `predicate(cp)` holds. Surrogates never hold."""
    out, start = [], None
    for cp in range(MAX):
        hit = False if cp in SURROGATES else bool(predicate(cp))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def table(name, rows, doc):
    flat = [v for row in rows for v in row]
    return "// %s\n// %d ranges covering %d code points.\nvar %s = [...]rune{\n%s\n}\n\n" % (
        doc, len(rows), sum(b - a + 1 for a, b in rows), name, wrap(flat))


def tok_array(cpp, go_name, cpp_name, values, doc, ctype="uint32_t"):
    """One generated array of the tokenizer tables, as Go (`var goName = [...]rune{`) or C++."""
    if cpp:
        return "// %s\ninline constexpr %s %s[] = {\n%s\n};\n\n" % (doc, ctype, cpp_name, wrap(values, indent="    "))
    gotype = "uint64" if ctype == "uint64_t" else "uint32" if ctype == "uint32_t" and go_name.endswith("Offsets") else "rune"
    return "// %s\nvar %s = [...]%s{\n%s\n}\n\n" % (doc, go_name, gotype, wrap(values))


def ascii_masks(name, predicate):
    low = sum(1 << cp for cp in range(0, 64) if predicate(cp))
    high = sum(1 << (cp - 64) for cp in range(64, 128) if predicate(cp))
    return "var %sASCII = [2]uint64{%#x, %#x}\n\n" % (name, low, high)


def header(source, extra=""):
    return ("// Code generated by laya-go/scripts/gen_tables.py from %s; DO NOT EDIT.\n"
            "//\n// Regenerate with: python laya-go/scripts/gen_tables.py\n%s\n" % (source, extra))


